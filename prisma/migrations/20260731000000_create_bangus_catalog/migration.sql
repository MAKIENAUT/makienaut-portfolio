CREATE TABLE "bangus_product_categories" (
  "id" UUID NOT NULL,
  "name" VARCHAR(80) NOT NULL,
  "sortOrder" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMPTZ(3) NOT NULL,

  CONSTRAINT "bangus_product_categories_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "bangus_product_categories_name_key"
  ON "bangus_product_categories"("name");

CREATE INDEX "bangus_product_categories_sortOrder_name_idx"
  ON "bangus_product_categories"("sortOrder", "name");

CREATE TABLE "bangus_products" (
  "id" UUID NOT NULL,
  "name" VARCHAR(120) NOT NULL,
  "supplierPrice" INTEGER NOT NULL,
  "retailPrice" INTEGER NOT NULL,
  "categoryId" UUID NOT NULL,
  "sizePack" VARCHAR(60) NOT NULL,
  "flavor" VARCHAR(60),
  "pieces" VARCHAR(60),
  "isActive" BOOLEAN NOT NULL DEFAULT true,
  "sortOrder" INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMPTZ(3) NOT NULL,

  CONSTRAINT "bangus_products_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "bangus_products_isActive_sortOrder_idx"
  ON "bangus_products"("isActive", "sortOrder");

CREATE INDEX "bangus_products_categoryId_sortOrder_idx"
  ON "bangus_products"("categoryId", "sortOrder");

ALTER TABLE "bangus_products"
  ADD CONSTRAINT "bangus_products_categoryId_fkey"
  FOREIGN KEY ("categoryId")
  REFERENCES "bangus_product_categories"("id")
  ON DELETE RESTRICT
  ON UPDATE CASCADE;

